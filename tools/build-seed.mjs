#!/usr/bin/env node
// Generates data/generated/seed.json and seed.js (the latter loads from file:// without fetch).
// Usage: node tools/build-seed.mjs   (run validate-data.mjs first; this refuses to build if validation fails)
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { ROOT, loadSource, assembleSeed } from './lib.mjs';
import { runChecks } from './validate-data.mjs';

const src = loadSource();
const results = runChecks(src);
const fails = results.filter((r) => r.status === 'FAIL');
if (fails.length) { console.error('Refusing to build: ' + fails.length + ' validation failure(s). Run node tools/validate-data.mjs'); process.exit(1); }
const seed = assembleSeed(src);
const json = JSON.stringify(seed, null, 2);
writeFileSync(path.join(ROOT, 'data/generated/seed.json'), json + '\n');
writeFileSync(path.join(ROOT, 'data/generated/seed.js'),
  '/* GENERATED by tools/build-seed.mjs from data/source/*.json — do not edit by hand. */\n' +
  'window.ECC_SEED = ' + json + ';\n' +
  'window.ECC_VALIDATION = ' + JSON.stringify({ dataVersion: seed.dataVersion, summary: results.reduce((a, r) => ((a[r.status] = (a[r.status] || 0) + 1), a), {}), results }) + ';\n');
console.log(`Seed built: ${seed.modules.length} modules, ${seed.lessons.length} lessons, ${seed.platformTests.length} tests/tracks, ${seed.discrepancies.length} discrepancies.`);
